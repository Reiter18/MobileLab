alter table public.bookings
    add column if not exists id bigint generated by default as identity,
    add column if not exists starts_at timestamptz,
    add column if not exists ends_at timestamptz,
    add column if not exists daily_price integer,
    add column if not exists daily_insurance integer,
    add column if not exists address text,
    add column if not exists cancelled boolean not null default false,
    add column if not exists request_id uuid;

update public.bookings b
set starts_at = b.created_at, ends_at = b.created_at + interval '72 hours',
    daily_price = c.price, daily_insurance = c.insurance, address = c.address
from public.cars c where c.id = b.car_id and b.starts_at is null;

alter table public.bookings
    alter column starts_at set not null, alter column ends_at set not null,
    alter column daily_price set not null, alter column daily_insurance set not null,
    alter column address set not null;

alter table public.bookings drop constraint if exists bookings_pkey;
alter table public.bookings add constraint bookings_pkey primary key (id);
create unique index if not exists bookings_request_key on public.bookings (user_id, request_id);
revoke insert, update, delete on public.bookings from anon, authenticated;

create or replace function public.lab4_book(car bigint, rental_start timestamptz, rental_end timestamptz, request_key uuid)
returns bigint
language plpgsql security definer set search_path = ''
as $$
declare
    owner_id uuid := auth.uid();
    item public.cars;
    booking_id bigint;
begin
    if owner_id is null or request_key is null then raise exception 'Войдите в аккаунт.'; end if;
    select * into strict item from public.cars where id = car for update;
    select id into booking_id from public.bookings where user_id = owner_id and request_id = request_key;
    if found then return booking_id; end if;

    if rental_start is null or rental_end is null or rental_start < now() - interval '1 minute'
       or rental_end <= rental_start then
        raise exception 'Проверьте даты начала и конца аренды.';
    end if;
    if exists (select 1 from public.bookings
        where car_id = car and not cancelled and starts_at < rental_end and ends_at > rental_start) then
        raise exception 'На это время автомобиль уже забронирован.';
    end if;

    insert into public.bookings (user_id, car_id, starts_at, ends_at, daily_price, daily_insurance, address, request_id)
    values (owner_id, car, rental_start, rental_end, item.price, item.insurance, item.address, request_key)
    returning id into booking_id;
    return booking_id;
end;
$$;

create or replace function public.lab4_cancel(booking bigint)
returns void
language plpgsql security definer set search_path = ''
as $$
begin
    update public.bookings set cancelled = true
    where id = booking and user_id = auth.uid() and ends_at > now();
    if not found then raise exception 'Это бронирование уже нельзя отменить.'; end if;
end;
$$;

revoke execute on function public.lab4_book(bigint, timestamptz, timestamptz, uuid) from public, anon;
revoke execute on function public.lab4_cancel(bigint) from public, anon;
grant execute on function public.lab4_book(bigint, timestamptz, timestamptz, uuid) to authenticated;
grant execute on function public.lab4_cancel(bigint) to authenticated;

notify pgrst, 'reload schema';
commit;
