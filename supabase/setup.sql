begin;

create table if not exists public.cars (
    id bigint generated by default as identity primary key,
    model text not null,
    brand text not null,
    price integer not null check (price > 0),
    transmission text not null,
    fuel text not null
);
alter table public.cars enable row level security;
revoke all on table public.cars from anon, authenticated;
grant select on table public.cars to authenticated;
drop policy if exists "Read catalog" on public.cars;
create policy "Read catalog" on public.cars for select to authenticated using (true);

insert into public.cars (model, brand, price, transmission, fuel)
select 'S 500 Sedan', 'Mercedes-Benz', 2500, 'A/T', 'Бензин'
from generate_series(1, 8)
where not exists (select 1 from public.cars);

create or replace function public.search_cars(term text)
returns setof public.cars
language sql stable security invoker set search_path = ''
as $$
    select c.* from public.cars c
    where btrim(coalesce(term, '')) = ''
       or strpos(lower(c.brand || ' ' || c.model), lower(btrim(term))) > 0
    order by c.id;
$$;
revoke execute on function public.search_cars(text) from public, anon;
grant execute on function public.search_cars(text) to authenticated;

create table if not exists public.registration_profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    first_name text not null,
    surname text not null,
    patronymic text,
    birth text not null,
    gender text not null,
    licence text not null,
    issued text not null
);
alter table public.registration_profiles enable row level security;
revoke all on table public.registration_profiles from anon, authenticated;
grant select, insert, update on table public.registration_profiles to authenticated;
drop policy if exists "Own registration profile" on public.registration_profiles;
create policy "Own registration profile" on public.registration_profiles for all to authenticated
    using (id = (select auth.uid())) with check (id = (select auth.uid()));

create table if not exists public.bookings (
    user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
    car_id bigint not null references public.cars(id) on delete cascade,
    created_at timestamptz not null default now(),
    primary key (user_id, car_id)
);
alter table public.bookings enable row level security;
revoke all on table public.bookings from anon, authenticated;
grant select, insert on table public.bookings to authenticated;
drop policy if exists "Own bookings" on public.bookings;
create policy "Own bookings" on public.bookings for all to authenticated
    using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('drive-private', 'drive-private', false, 6291456, array['image/jpeg'])
on conflict (id) do update set public = false, file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Own DriveNext photos" on storage.objects;
create policy "Own DriveNext photos" on storage.objects for all to authenticated
    using (bucket_id = 'drive-private' and (storage.foldername(name))[1] = (select auth.uid())::text)
    with check (bucket_id = 'drive-private' and (storage.foldername(name))[1] = (select auth.uid())::text);

commit;
